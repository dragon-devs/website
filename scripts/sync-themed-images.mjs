#!/usr/bin/env node
/**
 * Finds the images in public/ that ship in both themes.
 *
 * An asset is "themed" when `<name>-dark.<ext>` has a `<name>-light.<ext>`
 * sibling. Only those pairs are recorded, so ThemedImage can never swap to a
 * light file that was never exported — a missing pair simply renders the dark
 * one everywhere, rather than 404ing for half the visitors.
 *
 * Writes src/data/themed-images.generated.json. Runs on every build.
 */

import {existsSync, readdirSync, statSync, writeFileSync} from "node:fs";
import {dirname, join, relative, resolve, sep} from "node:path";
import {fileURLToPath} from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC_DIR = resolve(ROOT, "public");
const OUTPUT = resolve(ROOT, "src/data/themed-images.generated.json");

const DARK_SUFFIX = /-dark(\.[a-z0-9]+)$/i;

function walk(dir, found = []) {
    for (const entry of readdirSync(dir)) {
        const full = join(dir, entry);
        if (statSync(full).isDirectory()) walk(full, found);
        else found.push(full);
    }
    return found;
}

function main() {
    if (!existsSync(PUBLIC_DIR)) {
        console.warn("[sync-themed-images] no public/ directory; nothing to scan.");
        return;
    }

    const pairs = [];

    for (const file of walk(PUBLIC_DIR)) {
        if (!DARK_SUFFIX.test(file)) continue;
        const lightTwin = file.replace(DARK_SUFFIX, "-light$1");
        if (!existsSync(lightTwin)) continue;

        // Public paths are URLs, so always forward slashes.
        pairs.push(`/${relative(PUBLIC_DIR, file).split(sep).join("/")}`);
    }

    pairs.sort();

    writeFileSync(
        OUTPUT,
        `${JSON.stringify(
            {
                _generated:
                    "Generated by scripts/sync-themed-images.mjs. Do not edit — add <name>-dark and <name>-light pairs under public/ and rebuild.",
                dark: pairs,
            },
            null,
            2,
        )}\n`,
        "utf8",
    );

    console.log(`[sync-themed-images] ${pairs.length} themed image pairs found`);
}

main();
